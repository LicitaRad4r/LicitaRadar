import Fastify from 'fastify'

const app = Fastify({ logger: true })

const port = Number(process.env.PORT ?? 3333)

app.get('/health', async () => {
  return { status: 'ok', timestamp: new Date().toISOString() }
})

const start = async () => {
  try {
    await app.listen({ port, host: '0.0.0.0' })
  } catch (err) {
    app.log.error(err)
    process.exit(1)
  }
}

start()
